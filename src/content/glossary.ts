/**
 * 용어집 — 2026-08-08 리드가 준 정의 원문.
 *
 * 그동안 `밭갈이`·`영인지`·`왜곡씻기`·`이면유월`·`침`·`오픈/비오픈`·`신앙전환`은
 * 정의를 못 받아 **화면 문자열로만** 두고 코드 값으로 굳히지 않았다. 정의가 왔으므로
 * 이제 화면에서 뜻을 함께 보여 줄 수 있다.
 *
 * ⚠️ 정의가 왔다고 해서 **코드 값(enum · DB 코드 · 역할/스코프 코드)으로 굳히지는 않는다.**
 * 상담 테마는 여전히 번호로 저장하고, 자료실 폴더는 여전히 문자열이다. 굳혀서 얻는 것이
 * 없고, 표현이 다듬어질 때 후방 마이그레이션이 되기 때문이다(불변식 10).
 * 이 파일이 하는 일은 **뜻을 한 곳에 모아 화면에 설명으로 내보내는 것**뿐이다.
 *
 * ⚠️ 정의문은 **리드가 준 원문 그대로다. 요약·재작성하지 않는다** (불변식 5).
 * 표현을 고쳐야 하면 리드에게 확인한 뒤 이 파일에서만 고친다.
 */

export interface GlossaryTerm {
  /** 화면에 쓰는 이름 */
  term: string;
  /** 리드가 준 정의 원문 — 손대지 않는다 */
  definition: string;
  /** 같은 뜻으로 화면·폴더에 쓰이는 다른 표기 */
  aliases?: string[];
  /** 아직 확인이 남은 대목 */
  note?: string;
}

