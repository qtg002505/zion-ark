/** 이름으로 정의 찾기 — 별칭도 함께 본다 */
export function findTerm(name: string): GlossaryTerm | undefined {
  return ALL_TERMS.find((t) => t.term === name || t.aliases?.includes(name));
}

/** 그 테마에 붙는 정의들 */
export function termsForTheme(themeNo: number): GlossaryTerm[] {
  return (THEME_TERMS[themeNo] ?? [])
    .map(findTerm)
    .filter((t): t is GlossaryTerm => t !== undefined);
}
