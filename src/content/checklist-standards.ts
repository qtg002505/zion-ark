/** 총점 구간 — 이 그룹 번호들의 체크 합이 gradeA 이상이면 A, gradeB 이상이면 B, 미만이면 C */
export interface ChecklistSection {
  groupNos: number[];
  gradeA: number;
  gradeB: number;
}

